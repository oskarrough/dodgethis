// Collects the moba plugin's mods (docs/extending.md): one plain file per kind with static
// imports sorted by id. A folder is found by convention; this script is the only list.
// `bun run collect-mods` after adding or removing a folder; dev and check also collect.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

export const MOBA = fileURLToPath(new URL('../src/plugins/moba/', import.meta.url))

const HEADER = '// Generated by scripts/collect-mods.js (`bun run collect-mods`); do not edit.\n'
const KINDS = ['abilities', 'heroes', 'mechanics']

// Import names carry their kind, so an id may be a reserved word (`catch`).
const name = (id) => id.replace(/\W/g, '_')
const key = (id) => (/^[A-Za-z_$][\w$]*$/.test(id) ? id : `'${id}'`)
const entry = (id, value) => (key(id) === value ? value : `${key(id)}: ${value}`)
const folders = (kind) =>
	existsSync(join(MOBA, kind))
		? readdirSync(join(MOBA, kind), { withFileTypes: true })
				.filter((dirent) => dirent.isDirectory())
				.map((dirent) => dirent.name)
				.sort()
		: []
const has = (kind, id, file) => existsSync(join(MOBA, kind, id, file))
const object = (entries) =>
	entries.length ? `{\n${entries.map((line) => `\t${line},\n`).join('')}}` : '{}'

function manifests(kind) {
	const ids = folders(kind).filter((id) => has(kind, id, `${id}.js`))
	return (
		HEADER +
		ids.map((id) => `import ${name(`${kind}_${id}`)} from './${id}/${id}.js'\n`).join('') +
		(ids.length ? '\n' : '') +
		`export default ${object(ids.map((id) => entry(id, name(`${kind}_${id}`))))}\n`
	)
}

// The map table plus maps/recipes.js's lists and lookups, under the exports the game imports.
function maps() {
	const ids = folders('maps').filter((id) => has('maps', id, `${id}.js`))
	const imports = [
		...ids.map((id) => `import ${name(`maps_${id}`)} from './${id}/${id}.js'\n`),
		`import { mapRegistry } from './recipes.js'\n`,
	].sort()
	const entries = ids.map((id) => entry(id, name(`maps_${id}`)))
	return (
		HEADER +
		imports.join('') +
		`\nexport const DEFAULT_MAP = 'overthrow'\n` +
		`export const maps = ${object(entries)}\n` +
		`export const { playableMaps, onlineMaps, mapLayout, matchRecipe } = mapRegistry(maps, DEFAULT_MAP)\n`
	)
}

function tunes() {
	const imports = []
	const groups = ['abilities', 'heroes', 'maps'].map((kind) => {
		const ids = folders(kind).filter((id) => has(kind, id, `${id}-tune.js`))
		for (const id of ids)
			imports.push(`import ${name(`${kind}_${id}`)} from './${kind}/${id}/${id}-tune.js'\n`)
		return `export const ${kind} = ${object(ids.map((id) => entry(id, name(`${kind}_${id}`))))}\n`
	})
	return HEADER + imports.join('') + (imports.length ? '\n' : '') + groups.join('')
}

// One drawing entry per folder, namespace-imported with its named hooks.
function views(kind) {
	const imports = []
	const entries = folders(kind).flatMap((id) => {
		if (!has(kind, id, `${id}-view.js`)) return []
		const binding = name(`${id}_view`)
		imports.push(`import * as ${binding} from './${id}/${id}-view.js'\n`)
		return [entry(id, binding)]
	})
	return (
		HEADER + imports.join('') + (imports.length ? '\n' : '') + `export default ${object(entries)}\n`
	)
}

// Path (relative to the moba plugin) → the file's expected contents.
export function collectModFiles() {
	return {
		...Object.fromEntries(KINDS.map((kind) => [`${kind}/all-${kind}.js`, manifests(kind)])),
		'maps/all-maps.js': maps(),
		'all-tunes.js': tunes(),
		'heroes/all-hero-views.js': views('heroes'),
		'abilities/all-ability-views.js': views('abilities'),
		'maps/all-map-views.js': views('maps'),
		'mechanics/all-mechanic-views.js': views('mechanics'),
	}
}

if (import.meta.main)
	for (const [path, contents] of Object.entries(collectModFiles())) {
		const file = join(MOBA, path)
		if (existsSync(file) && readFileSync(file, 'utf8') === contents) continue
		mkdirSync(dirname(file), { recursive: true })
		writeFileSync(file, contents)
		console.log(`wrote src/plugins/moba/${path}`)
	}
